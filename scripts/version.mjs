#!/usr/bin/env node
// Single source of truth for the application version: the root package.json "version".
//
//   node scripts/version.mjs check                 verify every file agrees (exit 1 on mismatch)
//   node scripts/version.mjs set <semver>          write the version everywhere
//   node scripts/version.mjs bump <kind> [preid]   kind: major | minor | patch | prerelease
//
// Options: --root <dir> operate on another checkout (used by the tests).
//
// The application version (SemVer) is independent of the project file FORMAT_VERSION in
// packages/core/src/model.ts, which only changes when the saved file layout changes.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// https://semver.org (official regex)
const SEMVER =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/;

const PACKAGE_JSONS = ["package.json", "packages/core/package.json", "packages/host/package.json", "packages/mcp/package.json", "apps/desktop/package.json"];
const LOCK_WORKSPACES = { "": "package.json", "packages/core": "", "packages/host": "", "packages/mcp": "", "apps/desktop": "" };
const TAURI_CONF = "apps/desktop/src-tauri/tauri.conf.json";
const CARGO_TOML = "apps/desktop/src-tauri/Cargo.toml";
const CARGO_LOCK = "apps/desktop/src-tauri/Cargo.lock";
const PACKAGE_LOCK = "package-lock.json";
const VERSION_TS = "packages/core/src/version.ts";
const CRATE = "lumiere-pro";

const tauriRe = /^(\s*"version"\s*:\s*")[^"]+(")/m;
const cargoTomlRe = /^(version\s*=\s*")[^"]+(")/m;
const cargoLockRe = new RegExp(`(name = "${CRATE}"\\r?\\nversion = ")[^"]+(")`);
const versionTsRe = /APP_VERSION = "([^"]+)"/;

export const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const read = (root, rel) => readFileSync(path.join(root, rel), "utf8");
const write = (root, rel, text) => writeFileSync(path.join(root, rel), text);
const readJson = (root, rel) => JSON.parse(read(root, rel));
const writeJson = (root, rel, obj) => write(root, rel, JSON.stringify(obj, null, 2) + "\n");

export function isSemver(v) {
  return typeof v === "string" && SEMVER.test(v);
}

export function readVersion(root = defaultRoot) {
  return readJson(root, "package.json").version;
}

/** Returns [{file, found}] for every place that does not hold `expected`. */
export function checkVersions(root = defaultRoot, expected = readVersion(root)) {
  const problems = [];
  const expect = (file, found) => {
    if (found !== expected) problems.push({ file, found: found ?? "(missing)" });
  };
  if (!isSemver(expected)) problems.push({ file: "package.json", found: `${expected} (not valid SemVer)` });

  for (const f of PACKAGE_JSONS) expect(f, readJson(root, f).version);
  expect(TAURI_CONF, tauriRe.exec(read(root, TAURI_CONF))?.[0].match(/"([^"]+)"$/)?.[1]);
  expect(CARGO_TOML, cargoTomlRe.exec(read(root, CARGO_TOML))?.[0].match(/"([^"]+)"/)?.[1]);
  const lockText = existsSync(path.join(root, CARGO_LOCK)) ? read(root, CARGO_LOCK) : null;
  if (lockText !== null) expect(CARGO_LOCK, cargoLockRe.exec(lockText)?.[0].match(/version = "([^"]+)"/)?.[1]);
  if (existsSync(path.join(root, PACKAGE_LOCK))) {
    const lock = readJson(root, PACKAGE_LOCK);
    for (const ws of Object.keys(LOCK_WORKSPACES)) expect(`${PACKAGE_LOCK} (${ws || "root"})`, lock.packages?.[ws]?.version);
  }
  expect(VERSION_TS, versionTsRe.exec(read(root, VERSION_TS))?.[1]);
  return problems;
}

export function setVersion(root, version) {
  if (!isSemver(version)) throw new Error(`"${version}" is not a valid SemVer version (expected e.g. 1.2.3 or 1.2.3-rc.1)`);

  for (const f of PACKAGE_JSONS) {
    const pkg = readJson(root, f);
    pkg.version = version;
    writeJson(root, f, pkg);
  }
  write(root, TAURI_CONF, read(root, TAURI_CONF).replace(tauriRe, `$1${version}$2`));
  write(root, CARGO_TOML, read(root, CARGO_TOML).replace(cargoTomlRe, `$1${version}$2`));
  if (existsSync(path.join(root, CARGO_LOCK))) {
    write(root, CARGO_LOCK, read(root, CARGO_LOCK).replace(cargoLockRe, `$1${version}$2`));
  }
  if (existsSync(path.join(root, PACKAGE_LOCK))) {
    const lock = readJson(root, PACKAGE_LOCK);
    for (const ws of Object.keys(LOCK_WORKSPACES)) if (lock.packages?.[ws]) lock.packages[ws].version = version;
    if (lock.version !== undefined) lock.version = version;
    writeJson(root, PACKAGE_LOCK, lock);
  }
  write(
    root,
    VERSION_TS,
    `// Generated by scripts/version.mjs from the root package.json. Do not edit by hand.\nexport const APP_VERSION = "${version}";\n`,
  );
}

export function nextVersion(current, kind, preid = "rc") {
  const m = SEMVER.exec(current);
  if (!m) throw new Error(`current version "${current}" is not valid SemVer`);
  let [major, minor, patch] = [Number(m[1]), Number(m[2]), Number(m[3])];
  const pre = m[4];
  switch (kind) {
    case "major":
      return pre && minor === 0 && patch === 0 ? `${major}.0.0` : `${major + 1}.0.0`;
    case "minor":
      return pre && patch === 0 ? `${major}.${minor}.0` : `${major}.${minor + 1}.0`;
    case "patch":
      return pre ? `${major}.${minor}.${patch}` : `${major}.${minor}.${patch + 1}`;
    case "prerelease": {
      const parts = pre ? pre.split(".") : [];
      if (parts[0] === preid && /^\d+$/.test(parts[1] ?? "")) return `${major}.${minor}.${patch}-${preid}.${Number(parts[1]) + 1}`;
      return pre ? `${major}.${minor}.${patch}-${preid}.1` : `${major}.${minor}.${patch + 1}-${preid}.1`;
    }
    default:
      throw new Error(`unknown bump kind "${kind}" (use major, minor, patch or prerelease)`);
  }
}

function main(argv) {
  const args = [...argv];
  let root = defaultRoot;
  const ri = args.indexOf("--root");
  if (ri >= 0) {
    root = path.resolve(args[ri + 1] ?? "");
    args.splice(ri, 2);
  }
  const [cmd = "check", a, b] = args;
  try {
    if (cmd === "check") {
      const v = readVersion(root);
      const problems = checkVersions(root, v);
      if (problems.length) {
        console.error(`Version mismatch (expected ${v} from package.json):`);
        for (const p of problems) console.error(`  ${p.file}: ${p.found}`);
        console.error("Fix with: npm run version:set -- " + v);
        process.exit(1);
      }
      console.log(`All version fields agree: ${v}`);
    } else if (cmd === "set") {
      if (!a) throw new Error("usage: version.mjs set <semver>");
      setVersion(root, a);
      console.log(`Version set to ${a} in ${PACKAGE_JSONS.length + 5} places. Update CHANGELOG.md, then commit and tag v${a}.`);
    } else if (cmd === "bump") {
      const next = nextVersion(readVersion(root), a, b);
      setVersion(root, next);
      console.log(`Version bumped to ${next}. Update CHANGELOG.md, then commit and tag v${next}.`);
    } else {
      throw new Error(`unknown command "${cmd}" (check | set | bump)`);
    }
  } catch (e) {
    console.error(`version: ${e.message}`);
    process.exit(2);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
